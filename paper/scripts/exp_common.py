# -*- coding: utf-8 -*-
"""Helpers shared by the build_*.py scripts (experiments A-D).

Every build script reads only results/experiments/<EXP>/*.csv (exported by tools/export_results.py),
writes the paper tables to tables/<name>.{csv,tex} and the figures to figures/<name>.{pdf,png},
and checks a few values against the paper: a mismatch stops make_all.py.
"""
import math
import re
from pathlib import Path

import pandas as pd

from common import FIGURES, REPO, RESULTS, TABLES

EXP = RESULTS / "experiments"


def read(exp, name, **kw):
    p = EXP / exp / name
    if not p.exists():
        raise SystemExit(f"{p.relative_to(REPO)} missing: run tools/export_results.py first.")
    return pd.read_csv(p, **kw)


def rnd(x, d):
    """Round half away from zero (as in the paper tables), not banker's rounding."""
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return x
    q = 10 ** d
    return math.floor(abs(x) * q + 0.5) / q * (1 if x >= 0 else -1)


def f(x, d=3, sign=False, thousands=False):
    """Format a number for a LaTeX cell ('--' for missing values)."""
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "--"
    v = rnd(float(x), d)
    s = f"{v:+,.{d}f}" if sign else f"{v:,.{d}f}"
    if not thousands:
        s = s.replace(",", "")
    return s.replace("-", "$-$") if s.startswith("-") else s


def ci(lo, hi, d=3):
    return f"[{f(lo, d)}, {f(hi, d)}]"


class Checks:
    """Compare computed values with the values printed in the paper."""

    def __init__(self, name):
        self.name, self.n, self.bad = name, 0, []

    def eq(self, what, got, expected, tol=0.0):
        self.n += 1
        if isinstance(expected, str) or isinstance(got, str):
            ok = str(got) == str(expected)
        else:
            ok = abs(float(got) - float(expected)) <= tol + 1e-12
        if not ok:
            self.bad.append(f"{what}: got {got}, paper {expected}")

    def done(self):
        if self.bad:
            raise SystemExit(f"{self.name}: {len(self.bad)} of {self.n} checks against the paper failed:\n  "
                             + "\n  ".join(self.bad))
        print(f"{self.name}: {self.n} checks against the paper OK")


def write_table(stem, rows, header, caption, label, colspec=None, note=None):
    """Write tables/<stem>.csv (values as printed) and tables/<stem>.tex (booktabs table)."""
    TABLES.mkdir(parents=True, exist_ok=True)
    df = pd.DataFrame(table_rows_only(rows), columns=header)
    df.to_csv(TABLES / f"{stem}.csv", index=False, encoding="utf-8", lineterminator="\n")
    colspec = colspec or ("l" + "c" * (len(header) - 1))
    lines = [r"% Generated by paper/make_all.py - do not edit by hand.",
             r"\begin{table}[!ht]", rf"  \caption{{{caption}}}\label{{{label}}}", r"  \footnotesize",
             rf"  \begin{{tabular*}}{{\textwidth}}{{@{{\extracolsep\fill}}{colspec}@{{}}}}", r"  \toprule",
             "  " + " & ".join(rf"\textbf{{{h}}}" if h else "" for h in header) + r" \\", r"  \midrule"]
    for r in rows:
        if isinstance(r, str):  # raw LaTeX line (section rows, \midrule)
            lines.append("  " + r)
        else:
            cells, skip = [], 0
            for c in map(str, r):  # the cells spanned by a \multicolumn{k} (k - 1 empty cells) are dropped
                if skip and c == "":
                    skip -= 1
                    continue
                skip = 0
                m = re.match(r"\\multicolumn\{(\d+)\}", c)
                if m:
                    skip = int(m.group(1)) - 1
                cells.append(c)
            lines.append("  " + " & ".join(cells) + r" \\")
    lines += [r"  \bottomrule", r"  \end{tabular*}"]
    if note:
        lines.append(rf"  \footnotetext{{Note: {note}}}")
    lines.append(r"\end{table}")
    (TABLES / f"{stem}.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return TABLES / f"{stem}.tex"


def save_fig(fig, stem, **kw):
    FIGURES.mkdir(parents=True, exist_ok=True)
    out = []
    for ext in ("pdf", "png"):
        p = FIGURES / f"{stem}.{ext}"
        opts = dict(kw)
        if ext == "png":
            opts.setdefault("dpi", 300)
        fig.savefig(p, **opts)
        out.append(p)
    return out


def table_rows_only(rows):
    """Rows of write_table without the raw LaTeX lines (for the CSV)."""
    return [r for r in rows if not isinstance(r, str)]
